        FOREIGN KEY (don_vi_id, nguoi_moi_id)
        REFERENCES thanh_vien_don_vi(don_vi_id, id),

    CONSTRAINT ck_loi_moi_thoi_han CHECK (
        ngay_het_han > ngay_tao
