CREATE TABLE tac_gia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),

    ma_tac_gia VARCHAR(50) NOT NULL,
    ho_ten VARCHAR(200) NOT NULL,
    ten_hien_thi VARCHAR(200),
    ten_goc VARCHAR(200),
    ten_sap_xep VARCHAR(200),
    ten_khac VARCHAR(200),

    ngay_sinh DATE,
    nam_sinh SMALLINT,
    ngay_mat DATE,
    nam_mat SMALLINT,

    quoc_tich VARCHAR(100),
    quoc_gia_xuat_than VARCHAR(100),
    ngon_ngu_sang_tac VARCHAR(15),

    tieu_su_ngan TEXT,
    tieu_su_day_du TEXT,
    linh_vuc_sang_tac TEXT,
    thanh_tuu TEXT,
    website TEXT,
    url_tham_khao TEXT,

    anh_dai_dien_tep_id INTEGER REFERENCES tep_dinh_kem(id),
    nguon_du_lieu VARCHAR(80),

    trang_thai VARCHAR(24) NOT NULL DEFAULT 'DANG_DUNG'
        CHECK (
            trang_thai IN (
                'DANG_DUNG',
                'TAM_AN',
                'NGUNG_DUNG'
            )
        ),

    CONSTRAINT uq_tac_gia_ma
        UNIQUE (don_vi_id, ma_tac_gia),

    CONSTRAINT uq_tac_gia_tenant_id
        UNIQUE (don_vi_id, id),

    CONSTRAINT ck_tac_gia_nam CHECK (
        nam_mat IS NULL
        OR nam_sinh IS NULL
        OR nam_mat >= nam_sinh
    )
);

CREATE INDEX idx_tac_gia_ten
ON tac_gia (
    don_vi_id,
    lower(ho_ten)
);


CREATE TABLE ten_khac_tac_gia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),

    tac_gia_id INTEGER NOT NULL,
    ten VARCHAR(200) NOT NULL,

    loai_ten VARCHAR(30) NOT NULL
        CHECK (
            loai_ten IN (
                'BUT_DANH',
                'TEN_GOC',
                'PHIEN_AM',
                'TEN_KHAC'
            )
        ),

    ngon_ngu VARCHAR(15),
    la_ten_uu_tien BOOLEAN NOT NULL DEFAULT FALSE,
    ghi_chu TEXT,

    CONSTRAINT fk_ten_khac_tg
        FOREIGN KEY (don_vi_id, tac_gia_id)
        REFERENCES tac_gia(don_vi_id, id)
);

CREATE UNIQUE INDEX uq_ten_khac_tg
ON ten_khac_tac_gia (
    don_vi_id,
    tac_gia_id,
    loai_ten,
    lower(ten)
);


