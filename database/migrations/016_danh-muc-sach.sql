CREATE TABLE the_loai_sach (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),

    ma_the_loai VARCHAR(50) NOT NULL,
    ten_the_loai VARCHAR(200) NOT NULL,
    ten_tieng_anh VARCHAR(200),
    the_loai_cha_id INTEGER,

    mo_ta TEXT,
    duong_dan VARCHAR(240),
    thu_tu INTEGER NOT NULL DEFAULT 0,
    cap_do SMALLINT NOT NULL DEFAULT 1
        CHECK (cap_do >= 1),

    anh_dai_dien_tep_id INTEGER REFERENCES tep_dinh_kem(id),
    icon_tep_id INTEGER REFERENCES tep_dinh_kem(id),

    hien_thi_menu BOOLEAN NOT NULL DEFAULT TRUE,
    hien_thi_trang_chu BOOLEAN NOT NULL DEFAULT FALSE,

    trang_thai VARCHAR(24) NOT NULL DEFAULT 'DANG_DUNG'
        CHECK (
            trang_thai IN (
                'DANG_DUNG',
                'TAM_AN',
                'NGUNG_DUNG'
            )
        ),

    CONSTRAINT uq_the_loai_ma
        UNIQUE (don_vi_id, ma_the_loai),

    CONSTRAINT uq_the_loai_tenant_id
        UNIQUE (don_vi_id, id),

    CONSTRAINT fk_the_loai_cha
        FOREIGN KEY (don_vi_id, the_loai_cha_id)
        REFERENCES the_loai_sach(don_vi_id, id),

    CONSTRAINT ck_the_loai_khong_tu_cha CHECK (
        the_loai_cha_id IS NULL
        OR the_loai_cha_id <> id
    )
);

CREATE UNIQUE INDEX uq_the_loai_slug
ON the_loai_sach (
    don_vi_id,
    lower(duong_dan)
)
WHERE duong_dan IS NOT NULL;

CREATE INDEX idx_the_loai_cha
ON the_loai_sach (
    don_vi_id,
    the_loai_cha_id,
    thu_tu
);


CREATE TABLE tu_khoa_sach (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),

    ma_tu_khoa VARCHAR(60),
    ten_tu_khoa VARCHAR(120) NOT NULL,
    ten_chuan_hoa VARCHAR(120) NOT NULL,

    loai_tu_khoa VARCHAR(30) NOT NULL DEFAULT 'CHU_DE'
        CHECK (
            loai_tu_khoa IN (
                'CHU_DE',
                'KY_NANG',
                'NHAN_VAT',
                'SU_KIEN',
                'KHAC'
            )
        ),

    mo_ta TEXT,

    trang_thai VARCHAR(24) NOT NULL DEFAULT 'DANG_DUNG'
        CHECK (
            trang_thai IN (
                'DANG_DUNG',
                'TAM_AN',
                'NGUNG_DUNG'
            )
        ),

    CONSTRAINT uq_tu_khoa_chuan
        UNIQUE (
            don_vi_id,
            ten_chuan_hoa,
            loai_tu_khoa
        ),

    CONSTRAINT uq_tu_khoa_tenant_id
        UNIQUE (don_vi_id, id)
);

CREATE UNIQUE INDEX uq_tu_khoa_ma
ON tu_khoa_sach (
    don_vi_id,
    ma_tu_khoa
)
WHERE ma_tu_khoa IS NOT NULL;


DO $$
DECLARE
    ten_bang TEXT;
BEGIN
    FOREACH ten_bang IN ARRAY ARRAY[
        'tac_gia',
        'ten_khac_tac_gia',
        'nha_xuat_ban',
        'thuong_hieu_xuat_ban',
        'nha_phat_hanh',
        'the_loai_sach',
        'tu_khoa_sach'
    ]
    LOOP
        EXECUTE format(
            'CREATE TRIGGER %I
             BEFORE UPDATE ON public.%I
             FOR EACH ROW
             EXECUTE FUNCTION public.cap_nhat_ngay_cap_nhat()',
            'trg_' || ten_bang || '_ngay_cap_nhat',
            ten_bang
        );
    END LOOP;
END;
$$;