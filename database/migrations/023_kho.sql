    co_hut_am BOOLEAN NOT NULL DEFAULT FALSE,
    co_he_thong_chua_chay BOOLEAN NOT NULL DEFAULT FALSE,
    co_camera BOOLEAN NOT NULL DEFAULT FALSE,
    co_kiem_soat_ra_vao BOOLEAN NOT NULL DEFAULT FALSE,
    co_cam_bien_nhiet_do BOOLEAN NOT NULL DEFAULT FALSE,
