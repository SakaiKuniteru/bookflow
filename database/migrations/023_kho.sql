        REFERENCES chi_nhanh(don_vi_id, id),
    CONSTRAINT fk_kho_cha FOREIGN KEY (don_vi_id, kho_cha_id)
        REFERENCES kho(don_vi_id, id),
    CONSTRAINT fk_kho_anh FOREIGN KEY (don_vi_id, anh_dai_dien_tep_id)
        REFERENCES tep_dinh_kem(don_vi_so_huu_id, id),
    CONSTRAINT fk_kho_so_do FOREIGN KEY (don_vi_id, so_do_kho_tep_id)
        REFERENCES tep_dinh_kem(don_vi_so_huu_id, id),
    CONSTRAINT uq_kho_ma UNIQUE (don_vi_id, ma_kho),
    CONSTRAINT uq_kho_don_vi_id UNIQUE (don_vi_id, id),
    CONSTRAINT uq_kho_chi_nhanh_id UNIQUE (don_vi_id, chi_nhanh_id, id),
    CONSTRAINT ck_kho_khong_tu_lam_cha CHECK (kho_cha_id IS NULL OR kho_cha_id <> id),
    CONSTRAINT ck_kho_suc_chua CHECK (
        dien_tich_su_dung_m2 IS NULL OR dien_tich_m2 IS NULL
        OR dien_tich_su_dung_m2 <= dien_tich_m2
    ),
    CONSTRAINT ck_kho_nhiet_do CHECK (
        nhiet_do_toi_thieu_c IS NULL OR nhiet_do_toi_da_c IS NULL
        OR nhiet_do_toi_thieu_c <= nhiet_do_toi_da_c
    ),
    CONSTRAINT ck_kho_do_am CHECK (
        do_am_toi_thieu_phan_tram IS NULL OR do_am_toi_da_phan_tram IS NULL
        OR do_am_toi_thieu_phan_tram <= do_am_toi_da_phan_tram
    ),
    CONSTRAINT ck_kho_ngay CHECK (
        ngay_ngung_hoat_dong IS NULL OR ngay_bat_dau_hoat_dong IS NULL
        OR ngay_ngung_hoat_dong >= ngay_bat_dau_hoat_dong
    )
);
CREATE INDEX idx_kho_chi_nhanh ON kho (don_vi_id, chi_nhanh_id, trang_thai);
CREATE INDEX idx_kho_cha ON kho (don_vi_id, kho_cha_id);
CREATE UNIQUE INDEX uq_kho_mac_dinh
ON kho (don_vi_id, chi_nhanh_id)
WHERE la_kho_mac_dinh = TRUE AND ngay_xoa IS NULL;
CREATE UNIQUE INDEX uq_kho_nhan_mac_dinh
ON kho (don_vi_id, chi_nhanh_id)
WHERE la_kho_nhan_hang_mac_dinh = TRUE AND ngay_xoa IS NULL;
CREATE UNIQUE INDEX uq_kho_xuat_mac_dinh
ON kho (don_vi_id, chi_nhanh_id)
WHERE la_kho_xuat_hang_mac_dinh = TRUE AND ngay_xoa IS NULL;

