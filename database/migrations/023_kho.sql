    dia_chi_chi_tiet VARCHAR(350),
    ma_tinh_thanh VARCHAR(20),
    ten_tinh_thanh VARCHAR(120),
    ma_phuong_xa VARCHAR(20),
    ten_phuong_xa VARCHAR(120),
    ma_buu_chinh VARCHAR(20),
    quoc_gia CHAR(2) NOT NULL DEFAULT 'VN',
    vi_do NUMERIC(10,7) CHECK (vi_do BETWEEN -90 AND 90),
    kinh_do NUMERIC(10,7) CHECK (kinh_do BETWEEN -180 AND 180),
    huong_dan_duong_di TEXT,
    huong_dan_boc_do TEXT,
    cong_nhap_hang VARCHAR(80),
    cong_xuat_hang VARCHAR(80),
    so_dien_thoai VARCHAR(30),
    email VARCHAR(254),
    nguoi_quan_ly_id INTEGER REFERENCES tai_khoan(id),
    nguoi_phu_trach_nhap_id INTEGER REFERENCES tai_khoan(id),
    nguoi_phu_trach_xuat_id INTEGER REFERENCES tai_khoan(id),
