    suc_chua_toi_da_kg NUMERIC(15,3) CHECK (suc_chua_toi_da_kg > 0),
    dien_tich_m2 NUMERIC(15,3) CHECK (dien_tich_m2 > 0),
    dien_tich_su_dung_m2 NUMERIC(15,3) CHECK (dien_tich_su_dung_m2 > 0),
    chieu_cao_su_dung_m NUMERIC(10,3) CHECK (chieu_cao_su_dung_m > 0),
    the_tich_su_dung_m3 NUMERIC(15,3) CHECK (the_tich_su_dung_m3 > 0),
    nhiet_do_toi_thieu_c NUMERIC(6,2),
    nhiet_do_toi_da_c NUMERIC(6,2),
    do_am_toi_thieu_phan_tram NUMERIC(5,2)
        CHECK (do_am_toi_thieu_phan_tram BETWEEN 0 AND 100),
    do_am_toi_da_phan_tram NUMERIC(5,2)
        CHECK (do_am_toi_da_phan_tram BETWEEN 0 AND 100),
