CREATE TABLE IF NOT EXISTS giao_dich_thanh_toan (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    chi_nhanh_id INTEGER REFERENCES chi_nhanh(id),
    khach_hang_id INTEGER,
    phuong_thuc_id INTEGER NOT NULL,
    tai_khoan_nhan_id INTEGER,
    ma_giao_dich VARCHAR(100) NOT NULL,
    ma_giao_dich_doi_tac VARCHAR(200),
    ma_yeu_cau_doi_tac VARCHAR(200),
    loai_giao_dich VARCHAR(20) NOT NULL CHECK (loai_giao_dich IN ('THU','CHI','HOAN_TIEN')),
    so_tien NUMERIC(18,2) NOT NULL CHECK (so_tien > 0),
    tien_te CHAR(3) NOT NULL DEFAULT 'VND',
    trang_thai VARCHAR(25) NOT NULL DEFAULT 'KHOI_TAO' CHECK (trang_thai IN ('KHOI_TAO','CHO_XU_LY','THANH_CONG','THAT_BAI','DA_HUY','HET_HAN')),
    khoa_chong_trung VARCHAR(150),
    du_lieu_yeu_cau JSONB NOT NULL DEFAULT '{}'::jsonb,
    du_lieu_phan_hoi JSONB NOT NULL DEFAULT '{}'::jsonb,
    noi_dung TEXT,
    thoi_gian_het_han TIMESTAMPTZ,
    thoi_gian_thanh_cong TIMESTAMPTZ,
    nguoi_thuc_hien_id INTEGER REFERENCES tai_khoan(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (don_vi_id,ma_giao_dich),
    UNIQUE (don_vi_id,id),
    FOREIGN KEY (don_vi_id,khach_hang_id) REFERENCES khach_hang(don_vi_id,id),
    FOREIGN KEY (don_vi_id,phuong_thuc_id) REFERENCES phuong_thuc_thanh_toan(don_vi_id,id),
    FOREIGN KEY (don_vi_id,tai_khoan_nhan_id) REFERENCES tai_khoan_nhan_tien(don_vi_id,id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_giao_dich_thanh_toan_chong_trung ON giao_dich_thanh_toan(don_vi_id,khoa_chong_trung) WHERE khoa_chong_trung IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_giao_dich_thanh_toan ON giao_dich_thanh_toan(don_vi_id,trang_thai,ngay_tao DESC);
