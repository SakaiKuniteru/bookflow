CREATE TABLE IF NOT EXISTS cong_no (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    chi_nhanh_id INTEGER REFERENCES chi_nhanh(id),
    khach_hang_id INTEGER,
    nha_cung_cap_id INTEGER,
    ma_cong_no VARCHAR(80) NOT NULL,
    loai_cong_no VARCHAR(20) NOT NULL CHECK (loai_cong_no IN ('PHAI_THU','PHAI_TRA')),
    loai_nguon VARCHAR(30) NOT NULL CHECK (loai_nguon IN ('DON_HANG','PHIEU_NHAP','MUON_TRA','PHI_PHAT','DIEU_CHINH','KHAC')),
    nguon_id BIGINT,
    so_tien_goc NUMERIC(18,2) NOT NULL CHECK (so_tien_goc > 0),
    so_tien_da_thanh_toan NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (so_tien_da_thanh_toan >= 0),
    so_tien_da_giam NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (so_tien_da_giam >= 0),
    ngay_phat_sinh DATE NOT NULL DEFAULT CURRENT_DATE,
    ngay_den_han DATE,
    trang_thai VARCHAR(25) NOT NULL DEFAULT 'CHUA_THANH_TOAN' CHECK (trang_thai IN ('CHUA_THANH_TOAN','THANH_TOAN_MOT_PHAN','DA_THANH_TOAN','QUA_HAN','DA_XOA_NO','DA_HUY')),
    ghi_chu TEXT,
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (don_vi_id,ma_cong_no),
    UNIQUE (don_vi_id,id),
    FOREIGN KEY (don_vi_id,khach_hang_id) REFERENCES khach_hang(don_vi_id,id),
    CHECK (so_tien_da_thanh_toan + so_tien_da_giam <= so_tien_goc),
    CHECK ((loai_cong_no = 'PHAI_THU' AND khach_hang_id IS NOT NULL) OR (loai_cong_no = 'PHAI_TRA' AND nha_cung_cap_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_cong_no_den_han ON cong_no(don_vi_id,loai_cong_no,trang_thai,ngay_den_han);
