    CONSTRAINT fk_nccpbs_ncc FOREIGN KEY (don_vi_id, nha_cung_cap_id)
        REFERENCES nha_cung_cap(don_vi_id, id),
    CONSTRAINT fk_nccpbs_pb FOREIGN KEY (don_vi_id, phien_ban_sach_id)
        REFERENCES phien_ban_sach(don_vi_id, id),
    CONSTRAINT uq_nccpbs UNIQUE (don_vi_id, nha_cung_cap_id, phien_ban_sach_id),
    CONSTRAINT uq_nccpbs_don_vi_id UNIQUE (don_vi_id, id),
    CONSTRAINT ck_nccpbs_ngay CHECK (
        ngay_ket_thuc IS NULL OR ngay_bat_dau IS NULL OR ngay_ket_thuc >= ngay_bat_dau
    )
);
CREATE UNIQUE INDEX uq_nccpbs_uu_tien
ON nha_cung_cap_phien_ban_sach (don_vi_id, phien_ban_sach_id)
WHERE la_nha_cung_cap_uu_tien = TRUE AND trang_thai = 'DANG_CUNG_UNG';
CREATE INDEX idx_nccpbs_phien_ban ON nha_cung_cap_phien_ban_sach (don_vi_id, phien_ban_sach_id);

