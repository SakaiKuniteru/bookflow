    la_nha_cung_cap_uu_tien BOOLEAN NOT NULL DEFAULT FALSE,
    ngay_bat_dau DATE,
    ngay_ket_thuc DATE,
    ghi_chu TEXT,
    trang_thai VARCHAR(24) NOT NULL DEFAULT 'DANG_CUNG_UNG'
