    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),
    nha_cung_cap_id INTEGER NOT NULL,
    phien_ban_sach_id INTEGER NOT NULL,
    ma_sach_nha_cung_cap VARCHAR(100),
    ten_sach_nha_cung_cap VARCHAR(300),
    ma_vach_nha_cung_cap VARCHAR(100),
    don_vi_tinh VARCHAR(30) NOT NULL DEFAULT 'CUON',
    so_luong_moi_thung INTEGER CHECK (so_luong_moi_thung > 0),
    so_luong_dat_toi_thieu INTEGER CHECK (so_luong_dat_toi_thieu > 0),
    boi_so_dat_hang INTEGER CHECK (boi_so_dat_hang > 0),
    gia_nhap_tham_khao NUMERIC(18,2) CHECK (gia_nhap_tham_khao >= 0),
    don_vi_tien_te CHAR(3) NOT NULL DEFAULT 'VND',
    thue_suat_tham_khao NUMERIC(7,4) CHECK (thue_suat_tham_khao BETWEEN 0 AND 100),
    chiet_khau_tham_khao NUMERIC(7,4) CHECK (chiet_khau_tham_khao BETWEEN 0 AND 100),
