    ngay_ky DATE,
    ngay_hieu_luc DATE,
    ngay_het_han DATE,
    ngay_thanh_ly DATE,
    don_vi_tien_te CHAR(3) NOT NULL DEFAULT 'VND',
    gia_tri_hop_dong NUMERIC(18,2) CHECK (gia_tri_hop_dong >= 0),
    han_muc_cong_no NUMERIC(18,2) CHECK (han_muc_cong_no >= 0),
    so_ngay_thanh_toan INTEGER CHECK (so_ngay_thanh_toan >= 0),
    dieu_khoan_giao_hang TEXT,
    dieu_khoan_thanh_toan TEXT,
