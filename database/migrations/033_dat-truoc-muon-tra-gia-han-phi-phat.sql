CREATE TABLE IF NOT EXISTS muon_tra (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    chi_nhanh_id INTEGER REFERENCES chi_nhanh(id),
    khach_hang_id INTEGER NOT NULL,
    don_hang_id BIGINT,
    ma_phieu VARCHAR(80) NOT NULL,
    loai VARCHAR(20) NOT NULL CHECK (loai IN ('MUON','THUE')),
    trang_thai VARCHAR(25) NOT NULL DEFAULT 'NHAP' CHECK (trang_thai IN ('NHAP','CHO_GIAO','DANG_GIAO','DANG_MUON','TRA_MOT_PHAN','DA_TRA','QUA_HAN','DA_HUY')),
    ngay_bat_dau TIMESTAMPTZ,
    ngay_hen_tra TIMESTAMPTZ,
    ngay_tra_het TIMESTAMPTZ,
    phi_thue NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (phi_thue >= 0),
    tien_coc_id BIGINT,
    ghi_chu TEXT,
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_giao_id INTEGER REFERENCES tai_khoan(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (don_vi_id,ma_phieu),
    UNIQUE (don_vi_id,id),
    FOREIGN KEY (don_vi_id,khach_hang_id) REFERENCES khach_hang(don_vi_id,id),
    FOREIGN KEY (don_vi_id,don_hang_id) REFERENCES don_hang(don_vi_id,id),
    FOREIGN KEY (don_vi_id,tien_coc_id) REFERENCES tien_coc(don_vi_id,id),
    CHECK (ngay_hen_tra IS NULL OR ngay_bat_dau IS NULL OR ngay_hen_tra >= ngay_bat_dau)
);
