CREATE TABLE IF NOT EXISTS chinh_sach_phi_phat (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    chi_nhanh_id INTEGER REFERENCES chi_nhanh(id),
    ma VARCHAR(60) NOT NULL,
    ten VARCHAR(200) NOT NULL,
    loai VARCHAR(25) NOT NULL CHECK (loai IN ('QUA_HAN','MAT_SACH','HU_HONG','KHAC')),
    cach_tinh VARCHAR(25) NOT NULL CHECK (cach_tinh IN ('CO_DINH','THEO_NGAY','PHAN_TRAM_GIA_TRI','THEO_THUC_TE')),
    gia_tri NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (gia_tri >= 0),
    muc_toi_da NUMERIC(18,2) CHECK (muc_toi_da >= 0),
    so_ngay_mien_phi INTEGER NOT NULL DEFAULT 0 CHECK (so_ngay_mien_phi >= 0),
    dieu_kien JSONB NOT NULL DEFAULT '{}'::jsonb,
    hieu_luc_tu TIMESTAMPTZ NOT NULL,
    hieu_luc_den TIMESTAMPTZ,
