CREATE TABLE IF NOT EXISTS phi_phat (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    khach_hang_id INTEGER NOT NULL,
    chi_tiet_muon_tra_id BIGINT,
    chinh_sach_id INTEGER,
    ma_phieu VARCHAR(80) NOT NULL,
    loai VARCHAR(25) NOT NULL CHECK (loai IN ('QUA_HAN','MAT_SACH','HU_HONG','KHAC')),
    so_ngay_qua_han INTEGER NOT NULL DEFAULT 0 CHECK (so_ngay_qua_han >= 0),
    gia_tri_sach NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (gia_tri_sach >= 0),
    so_tien_goc NUMERIC(18,2) NOT NULL CHECK (so_tien_goc >= 0),
    so_tien_mien_giam NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (so_tien_mien_giam >= 0),
    so_tien_phai_thu NUMERIC(18,2) NOT NULL CHECK (so_tien_phai_thu >= 0),
    so_tien_da_thu NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (so_tien_da_thu >= 0),
    cong_no_id BIGINT,
    trang_thai VARCHAR(25) NOT NULL DEFAULT 'CHO_XAC_NHAN' CHECK (trang_thai IN ('CHO_XAC_NHAN','CHO_THU','THU_MOT_PHAN','DA_THU','DA_MIEN','DA_HUY')),
    ly_do TEXT,
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_duyet_id INTEGER REFERENCES tai_khoan(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_duyet TIMESTAMPTZ,
    UNIQUE (don_vi_id,ma_phieu),
    UNIQUE (don_vi_id,id),
    FOREIGN KEY (don_vi_id,khach_hang_id) REFERENCES khach_hang(don_vi_id,id),
    FOREIGN KEY (don_vi_id,chi_tiet_muon_tra_id) REFERENCES chi_tiet_muon_tra(don_vi_id,id),
    FOREIGN KEY (don_vi_id,chinh_sach_id) REFERENCES chinh_sach_phi_phat(don_vi_id,id),
    FOREIGN KEY (don_vi_id,cong_no_id) REFERENCES cong_no(don_vi_id,id),
    CHECK (so_tien_phai_thu = so_tien_goc - so_tien_mien_giam),
    CHECK (so_tien_da_thu <= so_tien_phai_thu)
);
