CREATE TABLE IF NOT EXISTS cuon_sach (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    phien_ban_sach_id INTEGER NOT NULL REFERENCES phien_ban_sach(id),
    kho_id INTEGER,
    vi_tri_kho_id INTEGER,
    ma_cuon VARCHAR(80) NOT NULL,
    ma_vach VARCHAR(100),
    rfid VARCHAR(150),
    so_serial VARCHAR(100),
    ngay_nhap DATE,
    gia_tri_sach NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (gia_tri_sach >= 0),
    tinh_trang VARCHAR(25) NOT NULL DEFAULT 'TOT' CHECK (tinh_trang IN ('MOI','TOT','DA_SU_DUNG','HU_HONG_NHE','HU_HONG_NANG','MAT')),
    trang_thai VARCHAR(25) NOT NULL DEFAULT 'SAN_SANG' CHECK (trang_thai IN ('SAN_SANG','DA_GIU','DANG_MUON','DANG_THUE','DANG_VAN_CHUYEN','BAO_TRI','MAT','THANH_LY')),
    mo_ta_tinh_trang TEXT,
