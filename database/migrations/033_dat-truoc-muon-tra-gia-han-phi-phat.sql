CREATE TABLE IF NOT EXISTS dat_truoc (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    chi_nhanh_id INTEGER REFERENCES chi_nhanh(id),
    khach_hang_id INTEGER NOT NULL,
    don_hang_id BIGINT,
    ma_dat_truoc VARCHAR(80) NOT NULL,
    trang_thai VARCHAR(25) NOT NULL DEFAULT 'CHO_SACH' CHECK (trang_thai IN ('CHO_SACH','CO_SACH','DA_THONG_BAO','CHO_NHAN','DA_NHAN','HET_HAN','DA_HUY')),
    muc_uu_tien INTEGER NOT NULL DEFAULT 0,
    ngay_dat TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_du_kien_co_sach TIMESTAMPTZ,
    ngay_het_han_nhan TIMESTAMPTZ,
    ngay_hoan_tat TIMESTAMPTZ,
    ghi_chu TEXT,
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (don_vi_id,ma_dat_truoc),
    UNIQUE (don_vi_id,id),
    FOREIGN KEY (don_vi_id,khach_hang_id) REFERENCES khach_hang(don_vi_id,id),
    FOREIGN KEY (don_vi_id,don_hang_id) REFERENCES don_hang(don_vi_id,id)
);
CREATE TABLE IF NOT EXISTS chi_tiet_dat_truoc (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL,
    dat_truoc_id BIGINT NOT NULL,
    phien_ban_sach_id INTEGER NOT NULL REFERENCES phien_ban_sach(id),
    hinh_thuc VARCHAR(20) NOT NULL CHECK (hinh_thuc IN ('MUA','MUON','THUE')),
    so_luong INTEGER NOT NULL CHECK (so_luong > 0),
    so_luong_da_phan_bo INTEGER NOT NULL DEFAULT 0 CHECK (so_luong_da_phan_bo >= 0),
    so_luong_da_nhan INTEGER NOT NULL DEFAULT 0 CHECK (so_luong_da_nhan >= 0),
    gia_du_kien NUMERIC(18,2) CHECK (gia_du_kien >= 0),
    ngay_du_kien DATE,
    ghi_chu TEXT,
    UNIQUE (don_vi_id,id),
    FOREIGN KEY (don_vi_id,dat_truoc_id) REFERENCES dat_truoc(don_vi_id,id),
    CHECK (so_luong_da_phan_bo <= so_luong),
    CHECK (so_luong_da_nhan <= so_luong_da_phan_bo)
);
