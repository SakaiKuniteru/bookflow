CREATE TABLE tep_sach (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),

    dau_sach_id INTEGER,
    phien_ban_sach_id INTEGER,
    tep_dinh_kem_id INTEGER NOT NULL REFERENCES tep_dinh_kem(id),

    loai_tep_sach VARCHAR(40) NOT NULL
        CHECK (
            loai_tep_sach IN (
                'ANH_BIA_TRUOC',
                'ANH_BIA_SAU',
                'ANH_GAY',
                'ANH_TRANG_TRONG',
                'ANH_HOP',
                'ANH_PHU',
                'MUC_LUC',
                'TRICH_DOAN',
                'VIDEO_GIOI_THIEU',
                'TAI_LIEU_KHAC'
            )
        ),

    thu_tu INTEGER NOT NULL DEFAULT 0
        CHECK (thu_tu >= 0),

    la_anh_bia_chinh BOOLEAN NOT NULL DEFAULT FALSE,
    tieu_de VARCHAR(200),
    mo_ta VARCHAR(500),
    van_ban_thay_the VARCHAR(300),
    chu_thich_ban_quyen TEXT,

    duoc_phep_cong_khai BOOLEAN NOT NULL DEFAULT FALSE,
    ngay_bat_dau_cong_khai TIMESTAMPTZ,
    ngay_ket_thuc_cong_khai TIMESTAMPTZ,

    trang_thai VARCHAR(24) NOT NULL DEFAULT 'DANG_DUNG'
        CHECK (
            trang_thai IN (
                'DANG_DUNG',
                'TAM_AN',
                'DA_GO'
            )
        ),

    CONSTRAINT ck_tep_sach_mot_chu CHECK (
        num_nonnulls(
            dau_sach_id,
            phien_ban_sach_id
        ) = 1
    ),

    CONSTRAINT fk_tep_sach_dau
        FOREIGN KEY (don_vi_id, dau_sach_id)
        REFERENCES dau_sach(don_vi_id, id),

    CONSTRAINT fk_tep_sach_pb
        FOREIGN KEY (don_vi_id, phien_ban_sach_id)
        REFERENCES phien_ban_sach(don_vi_id, id),

    CONSTRAINT ck_tep_sach_cong_khai CHECK (
        ngay_ket_thuc_cong_khai IS NULL
        OR ngay_bat_dau_cong_khai IS NULL
        OR ngay_ket_thuc_cong_khai > ngay_bat_dau_cong_khai
    )
);

CREATE UNIQUE INDEX uq_tep_sach_dau_file
