CREATE TABLE phien_ban_sach (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),

    -- Dinh danh va ten phien ban
    dau_sach_id INTEGER NOT NULL,
    ma_phien_ban VARCHAR(60) NOT NULL,
    ma_sku_noi_bo VARCHAR(80),
    ten_phien_ban VARCHAR(300),
    ten_hien_thi VARCHAR(350),

    -- ISBN va ma xuat ban
    isbn_10 VARCHAR(10)
        CHECK (
            isbn_10 IS NULL
            OR isbn_10 ~ '^[0-9]{9}[0-9X]$'
        ),

    isbn_13 VARCHAR(13)
        CHECK (
            isbn_13 IS NULL
            OR isbn_13 ~ '^[0-9]{13}$'
        ),

    ma_isbn VARCHAR(20)
        GENERATED ALWAYS AS (
            COALESCE(isbn_13, isbn_10)
        ) STORED,

    ma_ean_13 VARCHAR(13)
        CHECK (
            ma_ean_13 IS NULL
            OR ma_ean_13 ~ '^[0-9]{13}$'
        ),

    ma_vach_nha_xuat_ban VARCHAR(60),
    ma_san_pham_nha_xuat_ban VARCHAR(80),
    ma_luu_chieu VARCHAR(100),

    nhan_de_tren_bia VARCHAR(350),
    phu_de_phien_ban VARCHAR(350),
    ghi_chu_phien_ban TEXT,

    -- Xuat ban va phat hanh
    nha_xuat_ban_id INTEGER,
    thuong_hieu_xuat_ban_id INTEGER,
    nha_phat_hanh_id INTEGER,
    ten_nha_in VARCHAR(255),
    noi_xuat_ban VARCHAR(200),
    quoc_gia_xuat_ban VARCHAR(100),

    lan_xuat_ban SMALLINT
        CHECK (lan_xuat_ban > 0),
    lan_tai_ban SMALLINT
        CHECK (lan_tai_ban > 0),
    lan_in SMALLINT
        CHECK (lan_in > 0),
    so_ban_in INTEGER
        CHECK (so_ban_in > 0),

    nam_xuat_ban SMALLINT
        CHECK (nam_xuat_ban BETWEEN 1000 AND 9999),

    ngay_xuat_ban DATE,
    ngay_phat_hanh DATE,
    ngay_ngung_phat_hanh DATE,
    ghi_chu_lan_xuat_ban TEXT,

    -- Ngon ngu va dinh dang
    ngon_ngu_chinh VARCHAR(15) NOT NULL DEFAULT 'vi',
    ngon_ngu_goc VARCHAR(15),
    la_ban_dich BOOLEAN NOT NULL DEFAULT FALSE,
    la_ban_song_ngu BOOLEAN NOT NULL DEFAULT FALSE,

    loai_phien_ban VARCHAR(30) NOT NULL DEFAULT 'SACH_IN'
        CHECK (
            loai_phien_ban IN (
                'SACH_IN',
                'EBOOK',
                'SACH_NOI',
                'KHAC'
            )
        ),

    dinh_dang_noi_dung VARCHAR(30),

    -- Quy cach bia va giay
    loai_bia VARCHAR(24)
        CHECK (
            loai_bia IS NULL
            OR loai_bia IN (
                'BIA_MEM',
                'BIA_CUNG',
                'BIA_GAP',
                'KHAC'
            )
        ),

    chat_lieu_bia VARCHAR(100),
    kieu_dong_gay VARCHAR(80),
    chat_lieu_giay VARCHAR(100),

    dinh_luong_giay_gsm NUMERIC(8,2)
        CHECK (dinh_luong_giay_gsm > 0),

    loai_muc_in VARCHAR(80),
    so_mau_in SMALLINT
        CHECK (so_mau_in > 0),
    in_mau BOOLEAN,
    co_minh_hoa_mau BOOLEAN,

    -- Trang va cau truc
    so_trang INTEGER CHECK (so_trang > 0),
    so_trang_noi_dung INTEGER
        CHECK (so_trang_noi_dung > 0),
    so_trang_phu_luc INTEGER
        CHECK (so_trang_phu_luc >= 0),
    so_chuong INTEGER CHECK (so_chuong > 0),
    so_tap_trong_hop SMALLINT
        CHECK (so_tap_trong_hop > 0),
    so_quyen_trong_bo SMALLINT
        CHECK (so_quyen_trong_bo > 0),

    co_phu_luc BOOLEAN,
    co_dia_kem_theo BOOLEAN,
    so_dia_kem_theo SMALLINT
        CHECK (so_dia_kem_theo >= 0),

    -- Kich thuoc va trong luong
    chieu_dai_mm NUMERIC(8,2)
        CHECK (chieu_dai_mm > 0),
    chieu_rong_mm NUMERIC(8,2)
        CHECK (chieu_rong_mm > 0),
    do_day_mm NUMERIC(8,2)
        CHECK (do_day_mm > 0),
    trong_luong_gram INTEGER
        CHECK (trong_luong_gram > 0),

    chieu_dai_dong_goi_mm NUMERIC(8,2)
        CHECK (chieu_dai_dong_goi_mm > 0),
    chieu_rong_dong_goi_mm NUMERIC(8,2)
        CHECK (chieu_rong_dong_goi_mm > 0),
    chieu_cao_dong_goi_mm NUMERIC(8,2)
        CHECK (chieu_cao_dong_goi_mm > 0),
    trong_luong_dong_goi_gram INTEGER
        CHECK (trong_luong_dong_goi_gram > 0),

    -- Ebook va sach noi
    so_trang_dien_tu INTEGER
        CHECK (so_trang_dien_tu > 0),
    thoi_luong_am_thanh_giay INTEGER
        CHECK (thoi_luong_am_thanh_giay > 0),
    dinh_dang_am_thanh VARCHAR(30),
    toc_do_bit_am_thanh INTEGER
        CHECK (toc_do_bit_am_thanh > 0),
    dung_luong_noi_dung_byte BIGINT
        CHECK (dung_luong_noi_dung_byte > 0),

    co_drm BOOLEAN,
    loai_drm VARCHAR(50),
    dieu_kien_truy_cap_so TEXT,

    -- Gia bia tham khao
    gia_bia NUMERIC(18,2)
        CHECK (gia_bia >= 0),
    don_vi_tien_te CHAR(3) NOT NULL DEFAULT 'VND',

    -- Hinh anh va mo ta rieng
    anh_bia_chinh_id INTEGER REFERENCES tep_dinh_kem(id),
    mo_ta_rieng_phien_ban TEXT,
    ghi_chu_quy_cach TEXT,

    trang_thai VARCHAR(24) NOT NULL DEFAULT 'NHAP'
        CHECK (
            trang_thai IN (
                'NHAP',
                'DANG_DUNG',
                'TAM_NGUNG',
                'NGUNG_PHAT_HANH'
            )
        ),

    ngay_ngung_kinh_doanh TIMESTAMPTZ,
    ly_do_ngung TEXT,

    CONSTRAINT fk_pbs_dau_sach
        FOREIGN KEY (don_vi_id, dau_sach_id)
        REFERENCES dau_sach(don_vi_id, id),

    CONSTRAINT fk_pbs_nxb
        FOREIGN KEY (don_vi_id, nha_xuat_ban_id)
        REFERENCES nha_xuat_ban(don_vi_id, id),

    CONSTRAINT fk_pbs_thuong_hieu
        FOREIGN KEY (
            don_vi_id,
            nha_xuat_ban_id,
            thuong_hieu_xuat_ban_id
        )
        REFERENCES thuong_hieu_xuat_ban(
            don_vi_id,
            nha_xuat_ban_id,
            id
        ),

    CONSTRAINT fk_pbs_nph
        FOREIGN KEY (don_vi_id, nha_phat_hanh_id)
        REFERENCES nha_phat_hanh(don_vi_id, id),

    CONSTRAINT ck_pbs_thuong_hieu_can_nxb CHECK (
        thuong_hieu_xuat_ban_id IS NULL
        OR nha_xuat_ban_id IS NOT NULL
    ),

    CONSTRAINT ck_pbs_ngay_phat_hanh CHECK (
        ngay_ngung_phat_hanh IS NULL
        OR ngay_phat_hanh IS NULL
        OR ngay_ngung_phat_hanh >= ngay_phat_hanh
    ),

    CONSTRAINT ck_pbs_so_trang CHECK (
        so_trang IS NULL
        OR so_trang_noi_dung IS NULL
        OR so_trang >= so_trang_noi_dung
    ),

    CONSTRAINT uq_pbs_ma
        UNIQUE (don_vi_id, ma_phien_ban),

    CONSTRAINT uq_pbs_tenant_id
        UNIQUE (don_vi_id, id)
);

CREATE UNIQUE INDEX uq_pbs_isbn10
ON phien_ban_sach (
    don_vi_id,
    isbn_10
)
WHERE isbn_10 IS NOT NULL;

CREATE UNIQUE INDEX uq_pbs_isbn13
