DECLARE
    ten_bang TEXT;
BEGIN
    FOREACH ten_bang IN ARRAY ARRAY[
        'phien_ban_sach',
        'phien_ban_nguoi_dong_gop',
        'phien_ban_ngon_ngu',
        'phien_ban_ma_dinh_danh',
        'tep_sach',
        'nguon_du_lieu_sach',
        'quyen_noi_dung_sach'
    ]
    LOOP
        EXECUTE format(
            'CREATE TRIGGER %I
             BEFORE UPDATE ON public.%I
             FOR EACH ROW
             EXECUTE FUNCTION public.cap_nhat_ngay_cap_nhat()',
            'trg_' || ten_bang || '_ngay_cap_nhat',
            ten_bang
        );
    END LOOP;
END;
$$;