    dau_sach_id INTEGER,
    phien_ban_sach_id INTEGER,
    tep_dinh_kem_id INTEGER REFERENCES tep_dinh_kem(id),

    loai_noi_dung VARCHAR(40) NOT NULL,
    chu_so_huu_quyen VARCHAR(255),
    nguon_cap_quyen VARCHAR(255),
    loai_giay_phep VARCHAR(80),
    pham_vi_su_dung VARCHAR(100),

    duoc_hien_thi_cong_khai BOOLEAN NOT NULL DEFAULT FALSE,
    duoc_dung_cho_ai BOOLEAN NOT NULL DEFAULT FALSE,

    ngay_bat_dau DATE,
    ngay_het_han DATE,
