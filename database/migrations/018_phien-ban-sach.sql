)
WHERE phien_ban_sach_id IS NOT NULL
  AND la_anh_bia_chinh
  AND trang_thai = 'DANG_DUNG';

CREATE INDEX idx_tep_sach_thu_tu
ON tep_sach (
    don_vi_id,
