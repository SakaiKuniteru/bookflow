    don_vi_id,
    isbn_13
)
WHERE isbn_13 IS NOT NULL;

CREATE UNIQUE INDEX uq_pbs_sku
ON phien_ban_sach (
    don_vi_id,
    ma_sku_noi_bo
)
WHERE ma_sku_noi_bo IS NOT NULL;

CREATE INDEX idx_pbs_dau_sach
ON phien_ban_sach (
    don_vi_id,
    dau_sach_id,
    trang_thai
);


