                'BIEN_SOAN',
                'MINH_HOA',
                'HIEU_DINH',
                'BIEN_TAP',
                'KHAC'
            )
        ),

    thu_tu_hien_thi SMALLINT NOT NULL DEFAULT 1
        CHECK (thu_tu_hien_thi >= 1),

    la_nguoi_dong_gop_chinh BOOLEAN NOT NULL DEFAULT FALSE,
    ghi_chu VARCHAR(300),

    CONSTRAINT fk_dstg_sach
        FOREIGN KEY (don_vi_id, dau_sach_id)
        REFERENCES dau_sach(don_vi_id, id),

    CONSTRAINT fk_dstg_tac_gia
        FOREIGN KEY (don_vi_id, tac_gia_id)
        REFERENCES tac_gia(don_vi_id, id),

    CONSTRAINT uq_dstg
        UNIQUE (
            don_vi_id,
            dau_sach_id,
            tac_gia_id,
            vai_tro_dong_gop
        )
);


CREATE TABLE dau_sach_the_loai (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),

    dau_sach_id INTEGER NOT NULL,
    the_loai_id INTEGER NOT NULL,
    la_the_loai_chinh BOOLEAN NOT NULL DEFAULT FALSE,
    thu_tu_hien_thi SMALLINT NOT NULL DEFAULT 0
        CHECK (thu_tu_hien_thi >= 0),

    CONSTRAINT fk_dstl_sach
        FOREIGN KEY (don_vi_id, dau_sach_id)
        REFERENCES dau_sach(don_vi_id, id),

    CONSTRAINT fk_dstl_the_loai
        FOREIGN KEY (don_vi_id, the_loai_id)
        REFERENCES the_loai_sach(don_vi_id, id),

    CONSTRAINT uq_dstl
        UNIQUE (don_vi_id, dau_sach_id, the_loai_id)
);

CREATE UNIQUE INDEX uq_dstl_chinh
ON dau_sach_the_loai (
    don_vi_id,
    dau_sach_id
)
WHERE la_the_loai_chinh;


