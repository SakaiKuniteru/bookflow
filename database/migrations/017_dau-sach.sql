CREATE TABLE dau_sach (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),

    -- Dinh danh
    ma_dau_sach VARCHAR(50) NOT NULL,
    duong_dan VARCHAR(300),
    ma_dau_sach_ngoai VARCHAR(100),

    loai_tac_pham VARCHAR(30) NOT NULL DEFAULT 'SACH'
        CHECK (
            loai_tac_pham IN (
                'SACH',
                'TRUYEN_TRANH',
                'GIAO_TRINH',
                'TAP_CHI',
                'KHAC'
            )
        ),

    -- Nhan de
    ten_sach VARCHAR(300) NOT NULL,
    ten_goc VARCHAR(300),
    ten_phu VARCHAR(300),
    ten_ngan VARCHAR(160),
    ten_hien_thi VARCHAR(350),

    -- Noi dung
    mo_ta_ngan TEXT,
    mo_ta_day_du TEXT,
    tom_tat_noi_dung TEXT,
    diem_noi_bat TEXT,
    muc_luc_gioi_thieu TEXT,
    loi_gioi_thieu TEXT,
    thong_diep_tac_pham TEXT,

    -- Thong tin tac pham
    ngon_ngu_goc VARCHAR(15),
    quoc_gia_xuat_xu VARCHAR(100),
    nam_sang_tac SMALLINT,
    nam_xuat_ban_dau_tien SMALLINT,
    ngay_xuat_ban_hien_thi DATE,
    la_tac_pham_dich BOOLEAN NOT NULL DEFAULT FALSE,
    la_tac_pham_doc_lap BOOLEAN NOT NULL DEFAULT TRUE,

    -- Doc gia
    doi_tuong_doc VARCHAR(160),
    do_tuoi_goi_y SMALLINT
        CHECK (do_tuoi_goi_y >= 0),
    do_tuoi_toi_thieu SMALLINT
        CHECK (do_tuoi_toi_thieu >= 0),
    do_tuoi_toi_da SMALLINT
        CHECK (do_tuoi_toi_da >= 0),
    cap_hoc_goi_y VARCHAR(60),
    muc_do_kho VARCHAR(30),
    chu_de_noi_bat TEXT,
    canh_bao_noi_dung TEXT,
    ghi_chu_noi_dung TEXT,

    -- Anh bia mac dinh
    anh_bia_chinh_id INTEGER REFERENCES tep_dinh_kem(id),

    -- Nguon metadata
    nguon_du_lieu VARCHAR(80),
    ma_nguon_du_lieu VARCHAR(100),
    url_nguon TEXT,
    ngay_dong_bo_nguon TIMESTAMPTZ,
    nguoi_kiem_duyet_id INTEGER REFERENCES tai_khoan(id),
    ngay_kiem_duyet TIMESTAMPTZ,

    -- Hien thi cong khai
    tieu_de_seo VARCHAR(300),
    mo_ta_seo VARCHAR(500),
    cho_hien_thi_cong_khai BOOLEAN NOT NULL DEFAULT FALSE,
    ngay_cong_bo TIMESTAMPTZ,
    ngay_an TIMESTAMPTZ,
    ly_do_an TEXT,

    trang_thai VARCHAR(30) NOT NULL DEFAULT 'NHAP'
        CHECK (
            trang_thai IN (
                'NHAP',
                'CHO_DUYET',
                'DANG_HIEN_THI',
                'TAM_AN',
                'NGUNG_KINH_DOANH'
            )
        ),

    ngay_xoa TIMESTAMPTZ,

    CONSTRAINT uq_dau_sach_ma
        UNIQUE (don_vi_id, ma_dau_sach),

    CONSTRAINT uq_dau_sach_tenant_id
        UNIQUE (don_vi_id, id),

    CONSTRAINT ck_dau_sach_do_tuoi CHECK (
        do_tuoi_toi_thieu IS NULL
        OR do_tuoi_toi_da IS NULL
        OR do_tuoi_toi_da >= do_tuoi_toi_thieu
    )
);

CREATE UNIQUE INDEX uq_dau_sach_slug
ON dau_sach (
    don_vi_id,
    lower(duong_dan)
)
WHERE duong_dan IS NOT NULL;

CREATE INDEX idx_dau_sach_ten
ON dau_sach (
    don_vi_id,
    lower(ten_sach)
);

CREATE INDEX idx_dau_sach_trang_thai
ON dau_sach (
    don_vi_id,
    trang_thai,
    ngay_tao DESC
);


CREATE TABLE dau_sach_ten_khac (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),

    dau_sach_id INTEGER NOT NULL,
    ten VARCHAR(350) NOT NULL,

    loai_ten VARCHAR(30) NOT NULL
        CHECK (
            loai_ten IN (
                'TEN_GOC',
                'TEN_DICH',
                'TEN_CU',
                'TEN_VIET_TAT',
                'KHAC'
            )
        ),

    ngon_ngu VARCHAR(15),
    la_ten_uu_tien BOOLEAN NOT NULL DEFAULT FALSE,
    thu_tu SMALLINT NOT NULL DEFAULT 0
        CHECK (thu_tu >= 0),

    CONSTRAINT fk_dstk_sach
        FOREIGN KEY (don_vi_id, dau_sach_id)
        REFERENCES dau_sach(don_vi_id, id)
);

CREATE UNIQUE INDEX uq_dstk_ten
ON dau_sach_ten_khac (
    don_vi_id,
    dau_sach_id,
    loai_ten,
    lower(ten)
);


CREATE TABLE dau_sach_tac_gia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),

    dau_sach_id INTEGER NOT NULL,
    tac_gia_id INTEGER NOT NULL,

    vai_tro_dong_gop VARCHAR(30) NOT NULL DEFAULT 'TAC_GIA'
