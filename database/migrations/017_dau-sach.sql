                'PHAN_TRUOC',
                'BAN_MO_RONG',
                'TAI_LIEU_THAM_KHAO'
            )
        ),

    thu_tu SMALLINT NOT NULL DEFAULT 0
        CHECK (thu_tu >= 0),
    ghi_chu TEXT,

    CONSTRAINT fk_dslq_sach
        FOREIGN KEY (don_vi_id, dau_sach_id)
        REFERENCES dau_sach(don_vi_id, id),

    CONSTRAINT fk_dslq_sach_lien_quan
        FOREIGN KEY (don_vi_id, dau_sach_lien_quan_id)
        REFERENCES dau_sach(don_vi_id, id),

    CONSTRAINT uq_dslq
        UNIQUE (
            don_vi_id,
            dau_sach_id,
            dau_sach_lien_quan_id,
            loai_lien_quan
        ),

    CONSTRAINT ck_dslq_khong_tu_lien_quan CHECK (
        dau_sach_id <> dau_sach_lien_quan_id
    )
);


CREATE TABLE dau_sach_phan_loai (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    don_vi_id INTEGER NOT NULL REFERENCES don_vi(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
    nguoi_tao_id INTEGER REFERENCES tai_khoan(id),
    nguoi_cap_nhat_id INTEGER REFERENCES tai_khoan(id),

    dau_sach_id INTEGER NOT NULL,

    he_phan_loai VARCHAR(30) NOT NULL
        CHECK (
            he_phan_loai IN (
                'DDC',
                'LCC',
                'BISAC',
                'THEMA',
                'KHAC'
            )
        ),

    ma_phan_loai VARCHAR(60) NOT NULL,
    ten_phan_loai VARCHAR(255),
    phien_ban_he_phan_loai VARCHAR(50),
    la_phan_loai_chinh BOOLEAN NOT NULL DEFAULT FALSE,
    nguon_xac_minh TEXT,
    ngay_xac_minh TIMESTAMPTZ,

    CONSTRAINT fk_dspl_sach
        FOREIGN KEY (don_vi_id, dau_sach_id)
        REFERENCES dau_sach(don_vi_id, id),

    CONSTRAINT uq_dspl
        UNIQUE (
            don_vi_id,
            dau_sach_id,
            he_phan_loai,
            ma_phan_loai
        )
);


DO $$
DECLARE
    ten_bang TEXT;
BEGIN
    FOREACH ten_bang IN ARRAY ARRAY[
        'dau_sach',
        'dau_sach_ten_khac',
        'dau_sach_tac_gia',
        'dau_sach_the_loai',
        'dau_sach_tu_khoa',
        'bo_sach',
        'bo_sach_dau_sach',
        'dau_sach_lien_quan',
        'dau_sach_phan_loai'
    ]
    LOOP
        EXECUTE format(
            'CREATE TRIGGER %I
             BEFORE UPDATE ON public.%I
             FOR EACH ROW
             EXECUTE FUNCTION public.cap_nhat_ngay_cap_nhat()',
            'trg_' || ten_bang || '_ngay_cap_nhat',
            ten_bang
        );
    END LOOP;
END;
$$;